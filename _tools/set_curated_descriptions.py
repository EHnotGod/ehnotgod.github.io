def main():
    changed, missing = 0, []
    for md in sorted(BLOGS.rglob("index.md")):
        slug = md.parent.name
        if slug not in CURATED:
            missing.append(slug)
            continue
        text = md.read_text(encoding="utf-8")
        m = re.match(r"^(---\s*\n)(.*?)(\n---)", text, re.S)
        if not m:
            continue
        head, fm, tail = m.group(1), m.group(2), m.group(3)
        body = text[m.end():]
        desc = CURATED[slug].replace("\\", "\\\\").replace('"', '\\"')
        new_fm = re.sub(r"^description:.*$", f'description: "{desc}"', fm, count=1, flags=re.M)
        if new_fm != fm:
            md.write_text(head + new_fm + tail + body, encoding="utf-8")
            changed += 1

    print(f"== 更新了 {changed} 篇文章 ==")
    if missing:
        print(f"!! 未覆盖的 slug（{len(missing)}）: {missing}")


if __name__ == "__main__":
    main()
